import Foundation

enum ClipKind: String, CaseIterable, Identifiable {
  case text
  case rich
  case link
  case image
  case file

  var id: String { rawValue }

  var label: String {
    switch self {
    case .text: return "Text"
    case .rich: return "Rich text"
    case .link: return "Link"
    case .image: return "Image"
    case .file: return "File"
    }
  }

  var filterLabel: String {
    switch self {
    case .text: return "Text"
    case .rich: return "Rich"
    case .link: return "Links"
    case .image: return "Images"
    case .file: return "Files"
    }
  }
}

enum PasteboardPolicy {
  /// Marker Apple puts on Universal Clipboard payloads from a nearby iPhone, iPad, or Mac.
  static let remoteType = "com.apple.is-remote-clipboard"
  static let sourceType = "org.nspasteboard.source"

  /// http://nspasteboard.org — presence of any of these means the whole copy is skipped.
  static let ignoredTypes: Set<String> = [
    "org.nspasteboard.TransientType",
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "de.petermaurer.TransientPasteboardType",
    "Pasteboard generator type",
    "com.typeit4me.clipping",
    "net.antelle.keeweb",
  ]

  static let storedUTIs: Set<String> = [
    "public.utf8-plain-text",
    "public.rtf",
    "public.html",
    "public.url",
    "public.file-url",
    "public.png",
    "public.jpeg",
    "public.gif",
    "public.webp",
    "public.heic",
    "public.tiff",
    "public.pdf",
    "NSFilenamesPboardType",
  ]

  static let imageUTIs = [
    "public.png",
    "public.jpeg",
    "public.gif",
    "public.webp",
    "public.heic",
    "public.tiff",
  ]

  static func isIgnored(_ types: Set<String>) -> Bool {
    !types.isDisjoint(with: ignoredTypes)
  }

  static func byteCap(for uti: String) -> Int {
    switch uti {
    case "public.png", "public.jpeg", "public.gif", "public.webp", "public.heic", "public.tiff", "public.pdf":
      return 25_000_000
    case "public.rtf":
      return 2_000_000
    default:
      return 1_000_000
    }
  }
}

